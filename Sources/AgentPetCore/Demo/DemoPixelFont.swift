    private static let glyphsByCharacter: [Character: [String]] = compactGlyphsByCharacter.mapValues { rows in
        let width = rows.first?.count ?? 0
        let padding = Array(repeating: String(repeating: blank, count: width), count: max(0, glyphHeight - rows.count))
        return rows + padding
    }

    package static var characters: Set<Character> {
        Set(glyphsByCharacter.keys)
    }

    package static func glyphRows(for character: Character) -> [String]? {
        glyphsByCharacter[character]
    }

    package static func canRender(_ text: String) -> Bool {
        text.allSatisfy { character in glyphsByCharacter[character] != nil }
    }

    package static func width(of text: String) -> Int {
        let widths = text.compactMap { character in glyphsByCharacter[character]?.first?.count }
        guard !widths.isEmpty else { return 0 }
        return widths.reduce(0, +) + (widths.count - 1) * glyphSpacing
    }

    package static func wrap(_ text: String, maximumWidth: Int) -> [String] {
        var lines: [String] = []
        var current = ""
        for word in text.split(separator: " ").map(String.init) {
            let candidate = current.isEmpty ? word : current + " " + word
            if current.isEmpty || width(of: candidate) <= maximumWidth {
                current = candidate
            } else {
                lines.append(current)
                current = word
            }
        }
        if !current.isEmpty { lines.append(current) }
        return lines
    }

    package static func rows(for text: String) -> [String]? {
        guard canRender(text) else { return nil }
        let spacer = String(repeating: blank, count: glyphSpacing)
        return (0..<glyphHeight).map { rowIndex in
            text
                .compactMap { character in glyphsByCharacter[character]?[rowIndex] }
                .joined(separator: spacer)
        }
    }

    package static func isInk(_ character: Character) -> Bool {
        character == ink
    }
